"""Build the product with Claude Code, one gated phase at a time.

Run: uv run python scripts/run_build.py [product] [--phases n]

Every artifact under artifacts/builds/ is generated by this script. None of
them is a fixture written in advance.
"""

from __future__ import annotations

import sys
import time

from aml.build.evaluator import Evaluation
from aml.build.library import Library
from aml.build.orchestrator import GateBlocked, build
from aml.build.phases import PhaseSpec, order

APPROVER = "Head of Financial Crime Technology"


def approve(phase: PhaseSpec, evaluation: Evaluation, artifact: str) -> str:
    """Stands in for the human at the gate, and says so."""
    print(f"           GATE  {phase.name}: {evaluation.reason}", flush=True)
    print(f"           approved by {APPROVER}", flush=True)
    return APPROVER


def main() -> None:
    product = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else "aml-alert-investigator"
    limit = None
    if "--phases" in sys.argv:
        limit = int(sys.argv[sys.argv.index("--phases") + 1])

    phases = order()[:limit] if limit else order()
    print(f"building {product}: {len(phases)} phases\n")
    started = time.monotonic()

    def report(result) -> None:
        mark = "pass" if result.evaluation.passed else "FAIL"
        inherited = (f"  +{len(result.assets_inherited)} inherited"
                     if result.assets_inherited else "")
        print(f"  {mark}  {result.phase_id:16s} {result.evaluation.length:>6d} chars  "
              f"${result.cost_usd:.4f}  {result.duration_ms / 1000:5.1f}s"
              f"  {len(result.assets_created)} assets{inherited}", flush=True)

    try:
        record = build(
            product,
            library=Library(),
            approver=approve,
            generator=None,
            phases=phases,
            on_phase=report,
        )
    except GateBlocked as exc:
        print(f"\nBUILD BLOCKED: {exc}")
        sys.exit(1)

    elapsed = time.monotonic() - started
    lib = record["library"]
    print(f"\n{record['phases_passed']} of {record['phases_total']} phases passed, "
          f"every gate approved")
    print(f"cost ${record['cost_usd']:.4f}   wall {elapsed / 60:.1f} min")
    print(f"library: {lib['created']} created, {lib['inherited']} inherited, "
          f"reuse {lib['reuse_rate']:.0%}, {lib['on_disk']} assets on disk")
    print(f"artifacts in artifacts/builds/{product}/")


if __name__ == "__main__":
    main()
